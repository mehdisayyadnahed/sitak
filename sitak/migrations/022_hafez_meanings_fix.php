<?php
// اصلاح تفسیر چند بیت که با متن بیت هم‌خوانی نداشت؛ فقط وقتی تفسیر هنوز همان مقدار قدیمی باشد عوض می‌شود.
return static function (mysqli $conn): void {
    $fixes = [
        ['اگر آن ترک شیرازی به دست آرد دل ما را', 'گشاده‌دست و مهربان باش؛ طالع تو روشن است و از محبت دیگران بهره‌مند می‌شوی.', 'به دل‌بستگی‌های مادی بی‌اعتنا باش؛ آنچه واقعاً دل تو را می‌برد، ارزشش از همه‌ی داشته‌هایت بیشتر است.'],
        ['در ازل پرتو حسنت ز تجلی دم زد', 'با شجاعت در مسیر هدف قدم بردار؛ این راه پرارزش است و سختی‌هایش پاداش دارد.', 'عشق و اشتیاق تو شعله‌ور شده و همه‌چیز را به حرکت درمی‌آورد؛ با همین انگیزه مسیر را شروع کن.'],
        ['معاشران گره از زلف یار باز کنید', 'نگرانی‌ها از تو دور است؛ با قلبی مطمئن و شاد به سوی هدف حرکت کن.', 'شب خوش است، پس گره‌ها را باز کن و با دوستان همدل خوش بگذران؛ گفت‌وگوی صمیمی گره‌های دلت را می‌گشاید.'],
        ['دوش با من گفت پنهان کاردانی تیزهوش', 'سخت‌گیری بیش از حد را کنار بگذار؛ امور را آسان بگیر تا گشایش حاصل شود.', 'با آدم‌های امین و خردمند صادق باش؛ اسرارت را فقط با کسی در میان بگذار که واقعاً شایسته‌ی اعتمادش هستی.'],
    ];
    $st = $conn->prepare("UPDATE `hafez_verses` SET `meaning_short` = ? WHERE `verse_m1` = ? AND `meaning_short` = ?");
    if (!$st) throw new RuntimeException($conn->error);
    foreach ($fixes as [$m1, $oldMeaning, $newMeaning]) {
        $st->bind_param('sss', $newMeaning, $m1, $oldMeaning);
        if (!$st->execute()) throw new RuntimeException($conn->error);
    }
};
